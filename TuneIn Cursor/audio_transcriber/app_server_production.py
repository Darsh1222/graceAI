@app.route('/analyze', methods=['POST'])
def analyze():
    """Analyze performance endpoint with Supabase integration"""
    try:
        # Validate request
        if 'audio_file' not in request.files or 'sheet_music' not in request.files:
            return jsonify({'error': 'Missing required files'}), 400
        
        audio_file = request.files['audio_file']
        sheet_music_file = request.files['sheet_music']
        user_id = request.form.get('user_id')
        
        if not user_id:
            return jsonify({'error': 'Missing user_id'}), 400
        
        # Validate file types
        if not validate_file_type(audio_file.filename, ['m4a', 'wav', 'mp3']):
            return jsonify({'error': 'Invalid audio file type'}), 400
        
        if not validate_file_type(sheet_music_file.filename, ['pdf', 'jpg', 'jpeg', 'png', 'heic']):
            return jsonify({'error': 'Invalid sheet music file type'}), 400
        
        # Validate file sizes
        if not validate_file_size(len(audio_file.read()), MAX_CONTENT_LENGTH):
            return jsonify({'error': 'Audio file too large'}), 400
        
        audio_file.seek(0)  # Reset file pointer
        
        if not validate_file_size(len(sheet_music_file.read()), MAX_CONTENT_LENGTH):
            return jsonify({'error': 'Sheet music file too large'}), 400
        
        sheet_music_file.seek(0)  # Reset file pointer
        
        # Create temporary files
        with tempfile.NamedTemporaryFile(delete=False, suffix='.m4a', dir=UPLOAD_FOLDER) as audio_temp:
            audio_file.save(audio_temp.name)
            audio_path = audio_temp.name
        
        with tempfile.NamedTemporaryFile(delete=False, suffix='.pdf', dir=UPLOAD_FOLDER) as sheet_temp:
            sheet_music_file.save(sheet_temp.name)
            sheet_path = sheet_temp.name
        
        try:
            # Upload files to Supabase Storage
            logger.info(f"Uploading files to Supabase for user: {user_id}")
            
            audio_url, audio_filename = upload_file_to_supabase(audio_file, user_id, 'audio')
            sheet_music_url, sheet_music_filename = upload_file_to_supabase(sheet_music_file, user_id, 'sheet_music')
            
            if not audio_url or not sheet_music_url:
                logger.error("Failed to upload files to Supabase")
                return jsonify({'error': 'Failed to upload files'}), 500
            
            # Run analysis pipeline
            logger.info(f"Starting analysis for user: {user_id}")
            
            # Create output directory for processing
            output_dir = os.path.join(UPLOAD_FOLDER, f"analysis_{user_id}_{datetime.now().strftime('%Y%m%d_%H%M%S')}")
            os.makedirs(output_dir, exist_ok=True)
            
            # Process sheet music with cloud-installed tools
            logger.info("Processing sheet music with Audiveris and MuseScore...")
            try:
                sheet_midi_path = process_sheet_music_pipeline(sheet_path, output_dir)
                logger.info(f"Sheet music processed successfully: {sheet_midi_path}")
            except Exception as e:
                logger.error(f"Sheet music processing failed: {e}")
                # Fallback to audio-only analysis
                sheet_midi_path = None
            
            # Process audio with Basic Pitch
            logger.info("Processing audio with Basic Pitch...")
            try:
                from transcriber import transcribe_audio
                audio_midi_path = transcribe_audio(audio_path, output_dir)
                logger.info(f"Audio processed successfully: {audio_midi_path}")
            except Exception as e:
                logger.error(f"Audio processing failed: {e}")
                return jsonify({'error': 'Audio processing failed'}), 500
            
            # Run comparison analysis if both MIDI files exist
            if sheet_midi_path and audio_midi_path:
                logger.info("Running MIDI comparison analysis...")
                try:
                    from midi_comparison import compare_midi_files
                    analysis_data = compare_midi_files(sheet_midi_path, audio_midi_path)
                    success = True
                except Exception as e:
                    logger.error(f"MIDI comparison failed: {e}")
                    success = False
            else:
                logger.warning("Skipping MIDI comparison - missing sheet music MIDI")
                # Create basic analysis data for audio-only
                analysis_data = {
                    'accuracy': 0.0,
                    'correct_notes': 0,
                    'total_notes': 0,
                    'missed_notes': [],
                    'tempo_feedback': 'Sheet music processing unavailable',
                    'timing_feedback': 'Sheet music processing unavailable'
                }
                success = True
            
            if success:
                # Read analysis results
                import glob
                # Look for report files in the parent directory's generated_files folder
                parent_dir = os.path.dirname(os.path.dirname(__file__))
                report_files = glob.glob(os.path.join(parent_dir, 'generated_files', 'performance_report_*.json'))
                
                if report_files:
                    latest_report = max(report_files, key=os.path.getctime)
                    with open(latest_report, 'r') as f:
                        analysis_data = json.load(f)
                    
                    logger.info(f"Analysis data loaded: {analysis_data}")
                    
                    # Format results for API response - use actual data, not fallbacks
                    analysis_result = {
                        'accuracy': analysis_data.get('accuracy'),
                        'correctNotes': analysis_data.get('correct_notes'),
                        'totalNotes': analysis_data.get('total_notes'),
                        'missedNotes': analysis_data.get('missed_notes'),
                        'tempoFeedback': analysis_data.get('tempo_feedback'),
                        'timingFeedback': analysis_data.get('timing_feedback')
                    }
                    
                    # Validate that we have real data
                    if analysis_result['accuracy'] is None:
                        logger.error("No accuracy data found in analysis results")
                        return jsonify({'error': 'Analysis results incomplete'}), 500
                    
                    logger.info(f"Formatted analysis result: {analysis_result}")
                    
                    # Prepare session data for Supabase - match iOS app expectations
                    session_data = {
                        'user_id': user_id,
                        'date': datetime.now().isoformat(),  # iOS expects 'date' not 'created_at'
                        'audio_file_name': os.path.basename(audio_url) if audio_url else 'unknown_audio.m4a',
                        'sheet_music_file_name': os.path.basename(sheet_music_url) if sheet_music_url else 'unknown_sheet.pdf',
                        'piece_title': request.form.get('piece_title', ''),
                        'duration': float(request.form.get('duration', 0.0)),
                        'accuracy': analysis_result['accuracy'],
                        'correct_notes': analysis_result['correctNotes'],
                        'total_notes': analysis_result['totalNotes'],
                        'missed_notes': ','.join(analysis_result['missedNotes']) if isinstance(analysis_result['missedNotes'], list) else str(analysis_result['missedNotes']),
                        'tempo_feedback': analysis_result['tempoFeedback'],
                        'timing_feedback': analysis_result['timingFeedback']
                    }
                    
                    # Save session to Supabase
                    saved_session = save_session_to_supabase(session_data)
                    
                    # Update user statistics
                    update_user_stats(user_id, session_data)
                    
                    # Upload analysis results to Supabase storage
                    try:
                        # Find all result files
                        result_files = glob.glob(os.path.join(parent_dir, 'generated_files', '*'))
                        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
                        
                        for file_path in result_files:
                            if os.path.isfile(file_path):
                                filename = os.path.basename(file_path)
                                # Skip temporary files
                                if not filename.startswith('tmp'):
                                    with open(file_path, 'rb') as f:
                                        file_data = f.read()
                                    
                                    # Determine bucket based on file type
                                    if filename.endswith('.mid'):
                                        bucket_name = 'analysis-results'
                                        storage_path = f"{user_id}/midi_{timestamp}_{filename}"
                                    elif filename.endswith('.json'):
                                        bucket_name = 'analysis-results'
                                        storage_path = f"{user_id}/report_{timestamp}_{filename}"
                                    elif filename.endswith('.png'):
                                        bucket_name = 'analysis-results'
                                        storage_path = f"{user_id}/visualization_{timestamp}_{filename}"
                                    elif filename.endswith('.txt'):
                                        bucket_name = 'analysis-results'
                                        storage_path = f"{user_id}/summary_{timestamp}_{filename}"
                                    else:
                                        continue
                                    
                                    # Upload to Supabase
                                    supabase.storage.from_(bucket_name).upload(
                                        path=storage_path,
                                        file=file_data,
                                        file_options={"content-type": "application/octet-stream"}
                                    )
                                    logger.info(f"Uploaded {filename} to Supabase bucket '{bucket_name}': {storage_path}")
                        
                    except Exception as e:
                        logger.warning(f"Failed to upload analysis results to Supabase: {e}")
                    
                    # Add session_id to response
                    analysis_result['session_id'] = saved_session['id'] if saved_session else None
                    
                    logger.info(f"Analysis completed successfully for user: {user_id}")
                    
                    return jsonify(analysis_result)
                else:
                    return jsonify({'error': 'Analysis completed but no report found'}), 500
            else:
                return jsonify({'error': 'Analysis pipeline failed'}), 500
                
        finally:
            # Clean up temporary files
            try:
                os.unlink(audio_path)
                os.unlink(sheet_path)
            except Exception as e:
                logger.warning(f"Failed to clean up temporary files: {e}")
    
    except Exception as e:
        logger.error(f"Analysis error: {str(e)}")
        return jsonify({'error': f'Analysis failed: {str(e)}'}), 500

