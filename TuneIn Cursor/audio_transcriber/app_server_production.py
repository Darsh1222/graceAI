# Cloud Music Processing Functions
def process_sheet_music_with_audiveris(image_path, output_dir):
    """Process sheet music using cloud-installed Audiveris"""
    try:
        logger.info(f"Processing sheet music with Audiveris: {image_path}")
        
        # Use cloud-installed Audiveris
        audiveris_cmd = [
            "java", "-jar", "/usr/local/bin/audiveris.jar",
            "-batch",
            "-output", output_dir,
            image_path
        ]
        
        logger.info(f"Running Audiveris command: {' '.join(audiveris_cmd)}")
        result = subprocess.run(audiveris_cmd, capture_output=True, text=True, check=True, timeout=300)
        
        logger.info(f"Audiveris processing completed successfully")
        logger.info(f"Audiveris stdout: {result.stdout}")
        
        # Look for generated files
        base_name = os.path.splitext(os.path.basename(image_path))[0]
        omr_path = os.path.join(output_dir, f"{base_name}.omr")
        musicxml_path = os.path.join(output_dir, f"{base_name}.mxl")
        
        if os.path.exists(omr_path):
            logger.info(f"Found OMR file: {omr_path}")
            return omr_path
        elif os.path.exists(musicxml_path):
            logger.info(f"Found MusicXML file: {musicxml_path}")
            return musicxml_path
        else:
            # Look for any generated files
            for file in os.listdir(output_dir):
                if file.endswith(('.omr', '.mxl', '.xml')):
                    found_path = os.path.join(output_dir, file)
                    logger.info(f"Found generated file: {found_path}")
                    return found_path
            
            raise FileNotFoundError("No output files generated by Audiveris")
        
    except subprocess.CalledProcessError as e:
        logger.error(f"Audiveris processing failed: {e}")
        logger.error(f"Audiveris stderr: {e.stderr}")
        raise
    except subprocess.TimeoutExpired:
        logger.error("Audiveris processing timed out")
        raise
    except Exception as e:
        logger.error(f"Error in Audiveris processing: {e}")
        raise

def convert_musicxml_with_musescore(musicxml_path, output_dir):
    """Convert MusicXML to MIDI using cloud-installed MuseScore"""
    try:
        logger.info(f"Converting MusicXML to MIDI with MuseScore: {musicxml_path}")
        
        # Generate output MIDI path
        base_name = os.path.splitext(os.path.basename(musicxml_path))[0]
        midi_path = os.path.join(output_dir, f"{base_name}.mid")
        
        # Use cloud-installed MuseScore
        musescore_cmd = [
            "musescore3",
            "--export-to", midi_path,
            musicxml_path
        ]
        
        logger.info(f"Running MuseScore command: {' '.join(musescore_cmd)}")
        result = subprocess.run(musescore_cmd, capture_output=True, text=True, check=True, timeout=300)
        
        logger.info(f"MuseScore conversion completed successfully")
        logger.info(f"MuseScore stdout: {result.stdout}")
        
        if os.path.exists(midi_path):
            logger.info(f"MIDI file created: {midi_path}")
            return midi_path
        else:
            raise FileNotFoundError("MIDI file not found after MuseScore conversion")
        
    except subprocess.CalledProcessError as e:
        logger.error(f"MuseScore conversion failed: {e}")
        logger.error(f"MuseScore stderr: {e.stderr}")
        raise
    except subprocess.TimeoutExpired:
        logger.error("MuseScore conversion timed out")
        raise
    except Exception as e:
        logger.error(f"Error in MuseScore conversion: {e}")
        raise

def process_sheet_music_pipeline(image_path, output_dir):
    """Complete sheet music processing pipeline: Image -> MusicXML -> MIDI"""
    try:
        logger.info(f"Starting sheet music processing pipeline for: {image_path}")
        
        # Step 1: Process image with Audiveris
        logger.info("Step 1: Processing image with Audiveris...")
        audiveris_output = process_sheet_music_with_audiveris(image_path, output_dir)
        
        # Step 2: Convert to MIDI with MuseScore
        logger.info("Step 2: Converting to MIDI with MuseScore...")
        midi_path = convert_musicxml_with_musescore(audiveris_output, output_dir)
        
        logger.info(f"Sheet music processing pipeline completed successfully: {midi_path}")
        return midi_path
        
    except Exception as e:
        logger.error(f"Sheet music processing pipeline failed: {e}")
        raise

def upload_file_to_supabase(file, user_id, file_type):
    """Upload file to Supabase Storage"""
    try:
        if not supabase:
            logger.warning("Supabase not configured - skipping file upload")
            return None, None
            
        # Determine bucket based on file type
        if file_type == 'audio':
            bucket_name = 'user-audio'
        elif file_type == 'sheet_music':
            bucket_name = 'user-sheet-music'
        else:
            bucket_name = 'analysis-results'
            
        # Generate unique filename
        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        filename = f"{user_id}/{file_type}_{timestamp}_{secure_filename(file.filename)}"
        
        logger.info(f"Attempting to upload {file_type} file to bucket '{bucket_name}': {filename}")
        
        # Fix MIME type detection for PDFs
        content_type = file.content_type
        if file.filename.lower().endswith('.pdf'):
            content_type = 'application/pdf'
        elif file.filename.lower().endswith('.m4a'):
            content_type = 'audio/mp4'
        
        # Upload to Supabase Storage
        response = supabase.storage.from_(bucket_name).upload(
            path=filename,
            file=file.read(),
            file_options={"content-type": content_type}
        )
        
        # Get public URL
        file_url = supabase.storage.from_(bucket_name).get_public_url(filename)
        
        logger.info(f"File uploaded to Supabase bucket '{bucket_name}': {filename}")
        return file_url, filename
    except Exception as e:
        logger.error(f"Error uploading to Supabase: {str(e)}")
        logger.error(f"Error type: {type(e).__name__}")
        logger.error(f"Error details: {str(e)}")
        return None, None

def save_session_to_supabase(session_data):
    """Save practice session to Supabase database"""
    try:
        if not supabase:
            logger.warning("Supabase not configured - skipping session save")
            return None
            
        response = supabase.table('practice_sessions').insert(session_data).execute()
        saved_session = response.data[0] if response.data else None
        logger.info(f"Session saved to Supabase: {saved_session['id'] if saved_session else 'None'}")
        return saved_session
    except Exception as e:
        logger.error(f"Error saving session to Supabase: {str(e)}")
        return None

def update_user_stats(user_id, session_data):
    """Update user statistics in Supabase"""
    try:
        if not supabase:
            logger.warning("Supabase not configured - skipping stats update")
            return
            
        # Get current user stats
        response = supabase.table('user_profiles').select('*').eq('id', user_id).execute()
        current_stats = response.data[0] if response.data else {}
        
        # Calculate new stats
        new_total_sessions = current_stats.get('total_sessions', 0) + 1
        new_total_practice_time = current_stats.get('total_practice_time', 0) + session_data.get('duration', 0)
        
        # Update user profile
        supabase.table('user_profiles').upsert({
            'id': user_id,
            'total_sessions': new_total_sessions,
            'total_practice_time': new_total_practice_time,
            'average_accuracy': session_data.get('accuracy', 0),  # Will be calculated by trigger
            'best_accuracy': max(current_stats.get('best_accuracy', 0), session_data.get('accuracy', 0))
        }).execute()
        
        logger.info(f"User stats updated for user: {user_id}")
        
    except Exception as e:
        logger.error(f"Error updating user stats: {str(e)}")

def validate_file_type(filename, allowed_extensions):
    """Validate file type based on extension"""
    return '.' in filename and \
           filename.rsplit('.', 1)[1].lower() in allowed_extensions

def validate_file_size(file_size, max_size):
    """Validate file size"""
    return file_size <= max_size

